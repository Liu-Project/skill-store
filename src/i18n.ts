const TABLES: Record<Language, Record<MessageKey, string>> = {
  en: en as unknown as Record<MessageKey, string>,
  zh
};

let cachedLanguage: Language | undefined;

export function detectLanguage(): Language {
  if (cachedLanguage) {
    return cachedLanguage;
  }
  const language = (vscode.env as { language?: string } | undefined)?.language;
  cachedLanguage =
    typeof language === 'string' && language.toLowerCase().startsWith('zh')
      ? 'zh'
      : 'en';
  return cachedLanguage;
}

export function currentLanguage(): Language {
  return detectLanguage();
}

export function t(
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  const table = TABLES[detectLanguage()];
  let text = table[key] ?? TABLES.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function messages(): Record<string, string> {
  return { ...TABLES[detectLanguage()] };
}

export function resetLanguageCache(): void {
  cachedLanguage = undefined;
}
